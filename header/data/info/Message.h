/*
	对于字体颜色的设置（如何表示一段文字的某个部分颜色）我提供一个思路：
	可以使用“格式化代码”的方法，将颜色定义写在文本里面
	如：
	对于一段文字：
		text = "刘兴康大帅比";
		现在想把“刘兴康”改为蓝色，“大帅比”不改变
		在文本定义时不妨这样写：
		（“§”在键盘上打出的方式为：
			1.按住左Alt键不动
			2.在右侧小键盘处依次按下0167
			3.松开alt
			）
		text = "§b刘兴康§r大帅比";（解析这个颜色代码是这个类要做的）
		（这个"§b刘兴康§r大帅比"是要写到“资源文件/lang/”的两个json文件里面）

		其中 §r 可以用于重置文字样式。末尾一定要写§r

		§b指定其右方文字为红色，一直到下一个颜色代码（通常是§加小写字母或数字）

		颜色代码 你可以自己指定，也可以参考下面链接（有ANSI转义序列的部分 从 §0 到 §f）
		https://zh.minecraft.wiki/w/%E6%A0%BC%E5%BC%8F%E5%8C%96%E4%BB%A3%E7%A0%81
		（按住左Ctrl然后左键链接访问）
		只需要做 颜色代码（从 §0 到 §f部分）与（格式代码所有） 即可。

	如果文本想要包含字符“§”而不是将它当做颜色代码，可以这样写：
	test = "这是\§字符";（用"\"对§进行转义）
	输出：
		这是§字符
*/

